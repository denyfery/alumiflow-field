export function normalizeLocale(value: string | null | undefined): FieldLocale {
  return value === 'en' ? 'en' : 'id';
}

export function t(locale: FieldLocale, key: string, vars?: Vars): string {
  const template = locale === 'id' ? (id[key] ?? key) : key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function dateLocale(locale: FieldLocale): string {
  return locale === 'en' ? 'en-US' : 'id-ID';
}

